import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { sandbox, jsonl } from "./helpers.js";
import { applyEvent } from "../src/hook.js";
import { readLiveSession, liveSessionFile, normalizeUsage } from "../src/live.js";
import { readJSON } from "../src/store.js";
import { LogWatcher } from "../src/log-watcher.js";

const epoch = Date.now();
const stamp = (n) => new Date(epoch + n * 1000).toISOString();
test("conversation snapshots isolate models, usage, tools and elapsed time", (t) => {
  sandbox(t);
  const a = applyEvent({ type: "tool-start", sessionId: "A/unsafe", callId: "a1", tool: "bash", model: "o3", usage: { input_tokens: 100, output_tokens: 20, reasoning_output_tokens: 5, cached_input_tokens: 40 }, timestamp: stamp(0) });
  const b = applyEvent({ type: "turn-start", sessionId: "B", timestamp: stamp(1) });
  assert.equal(b.tokens, undefined);
  assert.equal(b.model, undefined);
  assert.equal(b.tool, undefined);
  assert.deepEqual(b.activeTools, []);
  assert.ok(b.startedAt > a.startedAt);
  assert.equal(readLiveSession("A/unsafe").tokens, 120);
  assert.deepEqual(a.usage, { input: 100, output: 20, reasoning: 5, cached: 40, total: 120 });
  assert.match(liveSessionFile("A/unsafe"), /^live\/codex-[a-f0-9]{64}\.json$/);
  applyEvent({ type: "thinking", sessionId: "A/unsafe", tokenOnly: true, usage: { total_tokens: 150 }, timestamp: stamp(0.5) });
  assert.equal(readJSON("state.json").sessionId, "B");
  assert.equal(readLiveSession("A/unsafe").tokens, 150);
  assert.equal(readLiveSession("A/unsafe").status, "working");
  assert.equal(readLiveSession("A/unsafe").tool, "bash");
});
test("parallel tools finish independently and duplicate calls count once", (t) => {
  sandbox(t);
  const event = { type: "function_call", sessionId: "chat", callId: "one", tool: "shell", timestamp: stamp(0) };
  applyEvent(event);
  applyEvent(event);
  let state = applyEvent({ ...event, callId: "two", tool: "apply_patch", timestamp: stamp(1) });
  assert.equal(state.observedToolCalls, 2);
  assert.equal(state.activeTools.length, 2);
  state = applyEvent({ type: "function_call_output", sessionId: "chat", callId: "one", timestamp: stamp(2) });
  assert.equal(state.status, "working");
  assert.equal(state.tool, "apply_patch");
  assert.equal(state.activeTools.length, 1);
  assert.equal(state.lastTool.name, "shell");
  state = applyEvent({ type: "function_call_output", sessionId: "chat", callId: "two", timestamp: stamp(3) });
  assert.equal(state.status, "thinking");
  assert.equal(state.tool, undefined);
  assert.equal(state.activeTools.length, 0);
  assert.equal(state.recentTools.length, 2);
  assert.equal(state.lastTool.durationMs, 2000);
  state = applyEvent({ ...event, timestamp: stamp(4) });
  assert.equal(state.status, "thinking");
  assert.equal(state.observedToolCalls, 2);
});
test("log tokens preserve each file's active tool and full thread usage", (t) => {
  const { codex } = sandbox(t);
  const dir = path.join(codex, "sessions");
  fs.mkdirSync(dir, { recursive: true });
  const a = path.join(dir, "a.jsonl"), b = path.join(dir, "b.jsonl");
  const row = (payload, n) => ({ type: "event_msg", timestamp: stamp(n), payload });
  jsonl(a, [{ type: "session_meta", payload: { id: "a" } }, row({ type: "function_call", name: "bash", call_id: "a1" }, 0)]);
  jsonl(b, [{ type: "session_meta", payload: { id: "b" } }, row({ type: "task_complete" }, 1)]);
  const watcher = new LogWatcher();
  watcher.poll();
  fs.appendFileSync(a, JSON.stringify(row({ type: "token_count", info: { total_token_usage: { input_tokens: 50, output_tokens: 25, total_tokens: 75, reasoning_output_tokens: 10 }, last_token_usage: { input_tokens: 10, output_tokens: 2 }, model_context_window: 128000 } }, 2)) + "\n");
  watcher.poll();
  const state = readLiveSession("a");
  assert.equal(state.status, "working");
  assert.equal(state.tool, "bash");
  assert.equal(state.tokens, 75);
  assert.equal(state.usage.reasoning, 10);
  assert.equal(state.lastUsage.total, 12);
  assert.equal(state.contextWindow, 128000);
  assert.equal(readLiveSession("b").status, "waiting");
  assert.equal(readLiveSession("b").tokens, undefined);
});
test("usage normalization rejects invalid counters and does not double-count reasoning", () => {
  assert.deepEqual(normalizeUsage({ input_tokens: 30, output_tokens: 20, reasoning_output_tokens: 10, cached_input_tokens: -1 }), { input: 30, output: 20, reasoning: 10, cached: 0, total: 50 });
});
